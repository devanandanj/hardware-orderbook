#!/usr/bin/env python3
"""
gen.py -- code generator for the wire-format specifications.

Every byte offset, field width, and endianness decision in this project lives
in the YAML files next to this script. This generator emits the same
constants into Verilog, C++, and Python so the RTL, the golden model, and the
host tooling cannot drift apart.

That drift is not hypothetical. Before this generator existed, the project had
two mutually incompatible book-snapshot formats -- one little-endian with
17-byte level records, one big-endian with 16-byte level records -- because
each was hand-written in a different repository.

Usage:
    python spec/gen.py                    # write generated files
    python spec/gen.py --outdir DIR       # write somewhere else
    python spec/gen.py --check            # verify on-disk files are current (CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

SPEC_DIR = Path(__file__).resolve().parent
DEFAULT_OUTDIR = SPEC_DIR / "generated"

BANNER = "Generated by spec/gen.py from spec/*.yaml. DO NOT EDIT BY HAND."

# Byte width -> Python struct format character. Widths with no native struct
# character (the 6-byte ITCH timestamp) fall back to a raw byte string.
STRUCT_CHAR_BY_WIDTH = {1: "B", 2: "H", 4: "I", 8: "Q"}


# --------------------------------------------------------------------------
# Loading and validation
# --------------------------------------------------------------------------

def load_specs() -> tuple[dict, dict, dict]:
    def load(name: str) -> dict:
        with open(SPEC_DIR / name, encoding="utf-8") as f:
            return yaml.safe_load(f)

    return load("itch.yaml"), load("moldudp64.yaml"), load("snapshot.yaml")


def check_contiguous(fields: list[dict], total: int, what: str) -> None:
    """Every byte between 0 and `total` must be claimed by exactly one field.

    This is the check that catches a mistyped offset, which is otherwise a
    silent wrong-field-decoded bug that shows up only as a scoreboard
    mismatch hundreds of messages into a run.
    """
    cursor = 0
    for field in fields:
        if field["offset"] != cursor:
            raise ValueError(
                f"{what}: field '{field['name']}' starts at byte "
                f"{field['offset']} but the previous field ends at {cursor}"
            )
        cursor += field["width"]

    if cursor != total:
        raise ValueError(
            f"{what}: fields span {cursor} bytes but declared length is {total}"
        )

    names = [f["name"] for f in fields]
    if len(names) != len(set(names)):
        raise ValueError(f"{what}: duplicate field name")


def validate(itch: dict, mold: dict, snap: dict) -> None:
    type_chars: dict[str, str] = {}

    for msg_name, msg in itch["messages"].items():
        check_contiguous(msg["fields"], msg["length"], f"itch.{msg_name}")

        first = msg["fields"][0]
        if first["name"] != "message_type" or first["width"] != 1:
            raise ValueError(
                f"itch.{msg_name}: must begin with a 1-byte message_type field"
            )

        char = msg["type_char"]
        if char in type_chars:
            raise ValueError(
                f"itch: type char '{char}' used by both "
                f"{type_chars[char]} and {msg_name}"
            )
        type_chars[char] = msg_name

    longest = max(m["length"] for m in itch["messages"].values())
    if itch["max_message_length"] != longest:
        raise ValueError(
            f"itch: max_message_length is {itch['max_message_length']} "
            f"but the longest message is {longest} bytes"
        )

    check_contiguous(mold["header"]["fields"], mold["header"]["length"],
                     "moldudp64.header")

    check_contiguous(snap["header"]["fields"], snap["header"]["length"],
                     "snapshot.header")
    check_contiguous(snap["level"]["fields"], snap["level"]["length"],
                     "snapshot.level")

    bits = [b["bit"] for b in snap["status_bits"]]
    if len(bits) != len(set(bits)):
        raise ValueError("snapshot: duplicate status bit position")
    if any(b < 0 or b > 7 for b in bits):
        raise ValueError("snapshot: status is one byte; bits must be 0..7")

    masked = {f["name"] for f in snap["header"]["fields"]}
    for name in snap["diff_masked_fields"]:
        if name not in masked:
            raise ValueError(
                f"snapshot: diff_masked_fields names '{name}', "
                f"which is not a header field"
            )


def snapshot_packet_length(snap: dict) -> int:
    """Length of ONE snapshot packet (one side).

    Each ITCH message emits `packets_per_message` such packets; the total
    egress volume per message is packet_length * packets_per_message. The
    MTU check in test_spec.py is against this per-packet length, since
    each packet is its own UDP datagram.
    """
    return snap["header"]["length"] + snap["max_orders_per_side"] * snap["level"]["length"]


def struct_format(fields: list[dict]) -> str:
    """Big-endian struct format string for a list of fields."""
    out = [">"]
    for field in fields:
        if field["type"] in ("ascii",):
            out.append(f"{field['width']}s")
        elif field["type"] == "char":
            out.append("c")
        elif field["width"] in STRUCT_CHAR_BY_WIDTH:
            out.append(STRUCT_CHAR_BY_WIDTH[field["width"]])
        else:
            # No native struct char for this width (e.g. the 6-byte ITCH
            # timestamp); carry it as raw bytes.
            out.append(f"{field['width']}s")
    return "".join(out)


# --------------------------------------------------------------------------
# Verilog
# --------------------------------------------------------------------------

VERILOG_PREAMBLE = """\
// {banner}
//
// Include this at FILE SCOPE, before your module. Everything here is a
// `define rather than a localparam so the file works outside a module body
// and stays legal in Verilog-2001 (required: Xilinx ISE/XST does not
// synthesize SystemVerilog).
//
// Byte-vector convention
// ----------------------
// Message bytes are accumulated into a flat vector with byte N at
// [8*N +: 8], i.e. the first byte received occupies the LOW 8 bits:
//
//     msg_buf[8*byte_count +: 8] <= s_axis_tdata;
//
// Fields are big-endian on the wire, so extracting one means reassembling
// its bytes in reverse. Use the `BE* macros below rather than writing the
// concatenations by hand.
//
//     wire [63:0] order_ref = `BE64(msg_buf, `ITCH_ADD_ORDER_ORDER_REF_OFF);

`ifndef ITCH_DEFS_VH
`define ITCH_DEFS_VH

// Big-endian field extraction from a byte-indexed vector.
`define BE8(buf, off)  (buf[8*(off) +: 8])
`define BE16(buf, off) {{buf[8*((off)+0) +: 8], buf[8*((off)+1) +: 8]}}
`define BE32(buf, off) {{buf[8*((off)+0) +: 8], buf[8*((off)+1) +: 8], \\
                        buf[8*((off)+2) +: 8], buf[8*((off)+3) +: 8]}}
`define BE48(buf, off) {{buf[8*((off)+0) +: 8], buf[8*((off)+1) +: 8], \\
                        buf[8*((off)+2) +: 8], buf[8*((off)+3) +: 8], \\
                        buf[8*((off)+4) +: 8], buf[8*((off)+5) +: 8]}}
`define BE64(buf, off) {{buf[8*((off)+0) +: 8], buf[8*((off)+1) +: 8], \\
                        buf[8*((off)+2) +: 8], buf[8*((off)+3) +: 8], \\
                        buf[8*((off)+4) +: 8], buf[8*((off)+5) +: 8], \\
                        buf[8*((off)+6) +: 8], buf[8*((off)+7) +: 8]}}
"""


def emit_verilog(itch: dict, mold: dict, snap: dict) -> str:
    out = [VERILOG_PREAMBLE.format(banner=BANNER)]
    add = out.append

    add("\n// ---- ITCH 5.0 ----\n")
    add(f"`define ITCH_MAX_MSG_LEN {itch['max_message_length']}\n")
    for msg_name, msg in itch["messages"].items():
        prefix = f"ITCH_{msg_name.upper()}"
        add(f"\n// {msg['type_char']} - {msg['comment'].strip()}\n")
        add(f"`define {prefix}_TYPE 8'h{ord(msg['type_char']):02X}"
            f"  // '{msg['type_char']}'\n")
        add(f"`define {prefix}_LEN {msg['length']}\n")
        for field in msg["fields"]:
            fname = field["name"].upper()
            add(f"`define {prefix}_{fname}_OFF {field['offset']}\n")
            add(f"`define {prefix}_{fname}_W {field['width']}\n")

    buy = itch["side_encoding"]["buy"]
    sell = itch["side_encoding"]["sell"]
    add("\n// Side encoding: wire char in, 1-bit internal representation out.\n")
    add(f"`define ITCH_SIDE_BUY_CHAR 8'h{ord(buy['wire_char']):02X}"
        f"  // '{buy['wire_char']}'\n")
    add(f"`define ITCH_SIDE_SELL_CHAR 8'h{ord(sell['wire_char']):02X}"
        f"  // '{sell['wire_char']}'\n")
    add(f"`define ITCH_SIDE_BUY 1'b{buy['internal']}\n")
    add(f"`define ITCH_SIDE_SELL 1'b{sell['internal']}\n")

    add("\n// ---- MoldUDP64 ----\n")
    add(f"`define MOLD_HDR_LEN {mold['header']['length']}\n")
    for field in mold["header"]["fields"]:
        fname = field["name"].upper()
        add(f"`define MOLD_{fname}_OFF {field['offset']}\n")
        add(f"`define MOLD_{fname}_W {field['width']}\n")
    add(f"`define MOLD_MSGLEN_W {mold['message_block']['length_field']['width']}\n")
    add(f"`define MOLD_HEARTBEAT 16'h{mold['control_counts']['heartbeat']:04X}\n")
    add("`define MOLD_END_OF_SESSION "
        f"16'h{mold['control_counts']['end_of_session']:04X}\n")

    add("\n// ---- Book snapshot (FPGA -> host, UDP payload) ----\n")
    add(f"`define SNAP_MAGIC 16'h{snap['magic']:04X}\n")
    add(f"`define SNAP_VERSION 8'd{snap['version']}\n")
    add(f"`define SNAP_HDR_LEN {snap['header']['length']}\n")
    add(f"`define SNAP_LEVEL_LEN {snap['level']['length']}\n")
    add(f"`define SNAP_MAX_PER_SIDE {snap['max_orders_per_side']}\n")
    add(f"`define SNAP_PACKETS_PER_MSG {snap['packets_per_message']}\n")
    add(f"`define SNAP_PACKET_LEN {snapshot_packet_length(snap)}"
        f"  // per-side UDP datagram; two per ITCH message\n")
    add("\n// side_id values -- match the internal 1-bit Side encoding.\n")
    add(f"`define SNAP_SIDE_ID_BIDS 8'd{itch['side_encoding']['buy']['internal']}\n")
    add(f"`define SNAP_SIDE_ID_ASKS 8'd{itch['side_encoding']['sell']['internal']}\n")
    for field in snap["header"]["fields"]:
        fname = field["name"].upper()
        add(f"`define SNAP_{fname}_OFF {field['offset']}\n")
        add(f"`define SNAP_{fname}_W {field['width']}\n")
    for field in snap["level"]["fields"]:
        fname = field["name"].upper()
        add(f"`define SNAP_LEVEL_{fname}_OFF {field['offset']}\n")
        add(f"`define SNAP_LEVEL_{fname}_W {field['width']}\n")
    add("\n// Snapshot status word bit positions.\n")
    for bit in snap["status_bits"]:
        add(f"`define SNAP_STATUS_{bit['name'].upper()} {bit['bit']}"
            f"  // {bit['comment']}\n")

    add("\n`endif // ITCH_DEFS_VH\n")
    return "".join(out)



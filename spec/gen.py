def emit_cpp(itch: dict, mold: dict, snap: dict, book: dict) -> str:
    out = [
        f"// {BANNER}\n"
        "//\n"
        "// Wire-format constants shared with the RTL (spec/generated/itch_defs.vh)\n"
        "// and the host tooling (spec/generated/itch_defs.py).\n"
        "\n"
        "#pragma once\n"
        "\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n"
        "\n"
    ]
    add = out.append

    add("// ---- ITCH 5.0 ----\n\n")
    add("inline constexpr std::size_t ITCH_MAX_MSG_LEN = "
        f"{itch['max_message_length']};\n\n")
    for msg_name, msg in itch["messages"].items():
        prefix = f"ITCH_{msg_name.upper()}"
        add(f"// {msg['type_char']} - {msg['comment'].strip()}\n")
        add(f"inline constexpr std::uint8_t {prefix}_TYPE = "
            f"'{msg['type_char']}';\n")
        add(f"inline constexpr std::size_t {prefix}_LEN = {msg['length']};\n")
        for field in msg["fields"]:
            fname = field["name"].upper()
            add(f"inline constexpr std::size_t {prefix}_{fname}_OFF = "
                f"{field['offset']};\n")
            add(f"inline constexpr std::size_t {prefix}_{fname}_W = "
                f"{field['width']};\n")
        add("\n")

    buy = itch["side_encoding"]["buy"]
    sell = itch["side_encoding"]["sell"]
    add("// Side encoding.\n")
    add(f"inline constexpr std::uint8_t ITCH_SIDE_BUY_CHAR = "
        f"'{buy['wire_char']}';\n")
    add(f"inline constexpr std::uint8_t ITCH_SIDE_SELL_CHAR = "
        f"'{sell['wire_char']}';\n\n")

    add("// ---- MoldUDP64 ----\n\n")
    add(f"inline constexpr std::size_t MOLD_HDR_LEN = "
        f"{mold['header']['length']};\n")
    for field in mold["header"]["fields"]:
        fname = field["name"].upper()
        add(f"inline constexpr std::size_t MOLD_{fname}_OFF = "
            f"{field['offset']};\n")
        add(f"inline constexpr std::size_t MOLD_{fname}_W = "
            f"{field['width']};\n")
    add(f"inline constexpr std::size_t MOLD_MSGLEN_W = "
        f"{mold['message_block']['length_field']['width']};\n")
    add(f"inline constexpr std::uint16_t MOLD_HEARTBEAT = "
        f"0x{mold['control_counts']['heartbeat']:04X};\n")
    add(f"inline constexpr std::uint16_t MOLD_END_OF_SESSION = "
        f"0x{mold['control_counts']['end_of_session']:04X};\n\n")

    add("// ---- Book snapshot (golden model -> trace, FPGA -> host) ----\n\n")
    add(f"inline constexpr std::uint16_t SNAP_MAGIC = 0x{snap['magic']:04X};\n")
    add(f"inline constexpr std::uint8_t SNAP_VERSION = {snap['version']};\n")
    add(f"inline constexpr std::size_t SNAP_PACKET_LEN = "
        f"{snap['packet']['length']};"
        f"  // one UDP datagram per ITCH message\n")
    for field in snap["packet"]["fields"]:
        fname = field["name"].upper()
        add(f"inline constexpr std::size_t SNAP_{fname}_OFF = "
            f"{field['offset']};\n")
        add(f"inline constexpr std::size_t SNAP_{fname}_W = "
            f"{field['width']};\n")
    add("\n// Snapshot status word bit positions.\n")
    for bit in snap["status_bits"]:
        add(f"inline constexpr std::uint8_t SNAP_STATUS_{bit['name'].upper()} = "
            f"{bit['bit']};  // {bit['comment']}\n")

    add("\n// ---- Order book geometry ----\n\n")
    for name, value in book_derived(book).items():
        add(f"inline constexpr std::uint32_t {name} = {value};\n")

    return "".join(out)



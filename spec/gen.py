def emit_python(itch: dict, mold: dict, snap: dict, book: dict) -> str:
    out = [
        f'"""{BANNER}\n'
        "\n"
        "Wire-format constants shared with the RTL and the C++ golden model.\n"
        "The STRUCT_FMT entries are ready for struct.pack/struct.unpack and are\n"
        "what the scapy stimulus generator and the UDP listener should use\n"
        "instead of hand-written format strings.\n"
        '"""\n\n'
    ]
    add = out.append

    add("# ---- ITCH 5.0 ----\n\n")
    add(f"ITCH_MAX_MSG_LEN = {itch['max_message_length']}\n\n")
    add("ITCH_MESSAGES = {\n")
    for msg_name, msg in itch["messages"].items():
        add(f"    {msg_name!r}: {{\n")
        add(f"        'type_char': {msg['type_char']!r},\n")
        add(f"        'length': {msg['length']},\n")
        add(f"        'struct_fmt': {struct_format(msg['fields'])!r},\n")
        add("        'fields': [\n")
        for field in msg["fields"]:
            add(f"            {{'name': {field['name']!r}, "
                f"'offset': {field['offset']}, "
                f"'width': {field['width']}, "
                f"'type': {field['type']!r}}},\n")
        add("        ],\n")
        add("    },\n")
    add("}\n\n")

    add("ITCH_BY_TYPE_CHAR = {\n")
    for msg_name, msg in itch["messages"].items():
        add(f"    {msg['type_char']!r}: {msg_name!r},\n")
    add("}\n\n")

    buy = itch["side_encoding"]["buy"]
    sell = itch["side_encoding"]["sell"]
    add(f"ITCH_SIDE_BUY_CHAR = {buy['wire_char']!r}\n")
    add(f"ITCH_SIDE_SELL_CHAR = {sell['wire_char']!r}\n")
    add(f"ITCH_SIDE_BUY = {buy['internal']}\n")
    add(f"ITCH_SIDE_SELL = {sell['internal']}\n\n")

    add("# ---- MoldUDP64 ----\n\n")
    add(f"MOLD_HDR_LEN = {mold['header']['length']}\n")
    add(f"MOLD_HDR_FMT = {struct_format(mold['header']['fields'])!r}\n")
    for field in mold["header"]["fields"]:
        fname = field["name"].upper()
        add(f"MOLD_{fname}_OFF = {field['offset']}\n")
        add(f"MOLD_{fname}_W = {field['width']}\n")
    add(f"MOLD_MSGLEN_W = {mold['message_block']['length_field']['width']}\n")
    add(f"MOLD_HEARTBEAT = 0x{mold['control_counts']['heartbeat']:04X}\n")
    add("MOLD_END_OF_SESSION = "
        f"0x{mold['control_counts']['end_of_session']:04X}\n\n")

    add("# ---- Book snapshot ----\n\n")
    add(f"SNAP_MAGIC = 0x{snap['magic']:04X}\n")
    add(f"SNAP_VERSION = {snap['version']}\n")
    add(f"SNAP_PACKET_LEN = {snap['packet']['length']}"
        f"  # one UDP datagram per ITCH message\n")
    add(f"SNAP_PACKET_FMT = {struct_format(snap['packet']['fields'])!r}\n")
    add("SNAP_PACKET_FIELDS = "
        f"{[f['name'] for f in snap['packet']['fields']]!r}\n\n")

    add("SNAP_STATUS_BITS = {\n")
    for bit in snap["status_bits"]:
        add(f"    {bit['name']!r}: {bit['bit']},  # {bit['comment']}\n")
    add("}\n\n")

    add("# Header fields the RTL-vs-model scoreboard must mask before\n"
        "# comparing: hardware cycle counters with no software equivalent.\n")
    add(f"SNAP_DIFF_MASKED_FIELDS = {snap['diff_masked_fields']!r}\n\n")

    add("# ---- Order book geometry ----\n\n")
    for name, value in book_derived(book).items():
        add(f"{name} = {value}\n")

    return "".join(out)


# --------------------------------------------------------------------------
# Driver
# --------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, default=DEFAULT_OUTDIR,
                        help="directory to write generated files into")
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if on-disk files are out of date")
    parser.add_argument("--book", type=Path,
                        help="book geometry to use instead of spec/book.yaml "
                             "(formal/ builds a small book this way)")
    args = parser.parse_args()

    itch, mold, snap, book = load_specs()
    if args.book:
        with open(args.book, encoding="utf-8") as f:
            book = yaml.safe_load(f)

    try:
        validate(itch, mold, snap)
        validate_book(book)
    except ValueError as exc:
        print(f"spec validation failed: {exc}", file=sys.stderr)
        return 1

    outputs = {
        "itch_defs.vh": emit_verilog(itch, mold, snap, book),
        "itch_defs.h": emit_cpp(itch, mold, snap, book),
        "itch_defs.py": emit_python(itch, mold, snap, book),
    }

    if args.check:
        stale = []
        for name, content in outputs.items():
            path = args.outdir / name
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        if stale:
            print("generated files are out of date: " + ", ".join(stale),
                  file=sys.stderr)
            print("run: python spec/gen.py", file=sys.stderr)
            return 1
        print(f"generated files are current ({len(outputs)} checked)")
        return 0

    args.outdir.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        path = args.outdir / name
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")

    print(f"\nsnapshot packet: {snap['packet']['length']} bytes, "
          f"one per ITCH message")

    b = book_derived(book)
    table_bits = (b["BOOK_SETS"] * b["BOOK_WAYS"] + b["BOOK_CAM_DEPTH"]) \
        * b["BOOK_ENTRY_W"]
    level_w = b["BOOK_LEVEL_SHARES_W"] + b["BOOK_LEVEL_ORDERS_W"]
    book_bits = 2 * b["BOOK_SLOTS"] * level_w
    print(f"order table: {b['BOOK_SETS']} sets x {b['BOOK_WAYS']} ways + "
          f"{b['BOOK_CAM_DEPTH']} CAM x {b['BOOK_ENTRY_W']} b = "
          f"{table_bits / 1e3:.0f} Kb")
    print(f"price books: 2 x {b['BOOK_SLOTS']} slots x {level_w} b = "
          f"{book_bits / 1e3:.0f} Kb  (total {(table_bits + book_bits) / 1e6:.2f} Mb)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
